function status = checkPaperArtifacts(cfg)
%CHECKPAPERARTIFACTS List the files read by paper_scl.tex and whether they exist.
%
%   status = checkPaperArtifacts(cfg)
%
%   Paths are interpreted relative to cfg.outputRoot (the paper's matlab/
%   folder).  status is a table with columns File, Role, Present, Bytes, and
%   is also printed.
P = cfg.paths;
sf = P.syntheticFigures; pf = P.parmaFigures; cd_ = P.captionData; cf = P.computeFigures;
list = { ...
    fullfile(sf,'01_error_observations.pdf'),      'Fig. 2(a)'; ...
    fullfile(sf,'02_error_outliers.pdf'),          'Fig. 2(b)'; ...
    fullfile(sf,'03_error_impurity.pdf'),          'Fig. 2(c)'; ...
    fullfile(sf,'04_error_sensors.pdf'),           'Fig. 2(d)'; ...
    fullfile(sf,'05_error_traveltime.pdf'),        'Fig. 2(e)'; ...
    fullfile(P.benchmarkFigures,'benchmark_error.pdf'), 'benchmark figure'; ...
    fullfile(P.benchmarkFigures,'integer_projection.pdf'), 'integer projection figure'; ...
    fullfile(cd_,'paper_results_integer.tex'),     'integer projection results'; ...
    fullfile(cd_,'paper_results_benchmark.tex'),   'benchmark table and settings'; ...
    fullfile(cd_,'paper_results_costsel.tex'),     'cost-aware selection results'; ...
    fullfile(cd_,'paper_results_missing.tex'),     'missing-routes results'; ...
    fullfile(P.benchmarkFigures,'cost_selection.pdf'), 'cost-aware selection figure'; ...
    fullfile(cd_,'paper_results_mle.tex'),         'comparison with the MLE'; ...
    fullfile(cd_,'paper_results_parma_estimators.tex'), 'Parma estimator comparison'; ...
    fullfile(sf,'simulation_settings.tex'),        'synthetic settings macros'; ...
    fullfile(pf,'01_sensors_directions.pdf'),      'Fig. 3'; ...
    fullfile(pf,'03_all_strata.pdf'),              'Fig. 4'; ...
    fullfile(pf,'02_peak_flows_by_day_type.pdf'),  'Fig. 5(a)'; ...
    fullfile(pf,'04_validation_violins.pdf'),      'Fig. 5(b)'; ...
    fullfile(cd_,'paper_caption_data.tex'),        'caption data macros'; ...
    fullfile(cd_,'paper_figure_captions.tex'),     'caption commands'; ...
    fullfile(cd_,'paper_results_synthetic.tex'),   'synthetic result macros'; ...
    fullfile(cd_,'paper_results_parma.tex'),       'Parma result macros'};
if isfield(cfg,'paperText') && ~cfg.paperText      % results and figures only: no .tex files
    list = list(~endsWith(string(list(:,1)),'.tex'),:);
end
n = size(list,1);
present = false(n,1); bytes = nan(n,1);
% Parma outputs are skipped, not missing, when no Parma results exist (the
% counts are not public; see buildPaperArtifacts>skipReason).
pm = P.parmaMat;
if ~(startsWith(pm,'/') || ~isempty(regexp(pm,'^[A-Za-z]:[\\/]','once'))), pm = fullfile(cfg.outputRoot,pm); end
hasParma = isfile(pm);
isParma = startsWith(string(list(:,1)),string(pf)) | contains(string(list(:,1)),'paper_results_parma');
skipped = isParma & ~hasParma;
for k = 1:n
    f = list{k,1};
    if ~(startsWith(f,'/') || ~isempty(regexp(f,'^[A-Za-z]:[\\/]','once')))
        f = fullfile(cfg.outputRoot,f);
    end
    present(k) = isfile(f);
    if present(k), d = dir(f); bytes(k) = d.bytes; end
end
status = table(string(list(:,1)),string(list(:,2)),present,bytes,skipped, ...
    'VariableNames',{'File','Role','Present','Bytes','Skipped'});
fprintf('Files read by the paper (relative to %s):\n',cfg.outputRoot);
for k = 1:n
    if present(k), tag = 'OK  '; elseif skipped(k), tag = 'SKIP'; else, tag = 'MISS'; end
    fprintf('  [%s] %-58s %s\n',tag,list{k,1},list{k,2});
end
if all(present | skipped)
    fprintf('All %d required files present',nnz(~skipped));
    if any(skipped), fprintf(' (%d Parma files skipped: no Parma results)',nnz(skipped)); end
    fprintf('. Compile the paper.\n');
else
    fprintf('%d of %d files missing.\n',nnz(~present & ~skipped),n);
end
end
